#!/bin/sh
# Print the Homebrew formula of a program of a release.
#
#   packaging/homebrew/formula.sh <version> <dist dir> [owner/repo] [program] > <program>.rb
#
# program: tracebridge (the default) or rvdbg, which also installs the
# patched OpenOCD (openocd-stellar) from the same tap.
#
# <dist dir> holds the release archives' .sha256 files
# (<program>-<target>.tar.gz.sha256) and, when present, the bottles' .sha256
# files from bottles.sh; those add a bottle block, so Homebrew pours the
# bottle instead of "building" (which requires the Command Line Tools). The Update formulae workflow of
# haoyibits/homebrew-tap downloads this script from the release tag, runs it
# and commits the result.
set -eu

version="${1:?version, e.g. 0.1.0}"
dist="${2:?directory with the .sha256 files}"
repo="${3:-haoyibits/tracebridge}"
program="${4:-tracebridge}"
base="https://github.com/$repo/releases/download/v$version"

case "$program" in
    tracebridge)
        class=Tracebridge
        desc="Drive Lauterbach TRACE32 PowerView from the command-line, VS Code and RustRover"
        dependencies=""
        ;;
    rvdbg)
        class=Rvdbg
        desc="Flash and debug rustvisor through TRACE32 or StellarLINK"
        dependencies='
  # The StellarLINK backend runs this patched OpenOCD.
  depends_on "haoyibits/tap/openocd-stellar"
'
        ;;
    *) echo "formula.sh: unknown program $program" >&2; exit 1 ;;
esac

bottle_block() {
    lines=""
    for tag in arm64_sonoma arm64_linux x86_64_linux; do
        file="$dist/$program-$version.$tag.bottle.tar.gz.sha256"
        [ -f "$file" ] || continue
        # brew style wants the digests aligned (longest tag is 12 characters).
        lines="$lines$(printf '    sha256 cellar: :any_skip_relocation, %-13s "%s"' "$tag:" "$(cut -d ' ' -f 1 "$file")")
"
    done
    [ -n "$lines" ] || return 0
    printf '\n  bottle do\n    root_url "%s"\n%s  end\n' "$base" "$lines"
}

sha() {
    file="$dist/$program-$1.tar.gz.sha256"
    [ -f "$file" ] || { echo "formula.sh: missing $file" >&2; exit 1; }
    cut -d ' ' -f 1 "$file"
}

cat <<FORMULA
# Generated by packaging/homebrew/formula.sh for $program $version; do not edit.
class $class < Formula
  desc "$desc"
  homepage "https://github.com/$repo"
  version "$version"
  license "MIT"
$(bottle_block)
$dependencies
  on_macos do
    # Intel Macs are not supported.
    depends_on arch: :arm64
    on_arm do
      url "$base/$program-aarch64-apple-darwin.tar.gz"
      sha256 "$(sha aarch64-apple-darwin)"
    end
  end

  on_linux do
    on_arm do
      url "$base/$program-aarch64-unknown-linux-musl.tar.gz"
      sha256 "$(sha aarch64-unknown-linux-musl)"
    end
    on_intel do
      url "$base/$program-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$(sha x86_64-unknown-linux-musl)"
    end
  end

  def install
    bin.install "$program"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/$program --version")
  end
end
FORMULA
